"""카메라를 언제 켤지 정한다 — 사용자 발화의 키워드로 판별한다.

**매 턴 카메라를 켜지 않는다.** 이미지가 붙으면 프롬프트 뒤에 토큰이 얹혀
프리픽스 캐시가 그 지점부터 깨지고, 실측(2026-09-09, gemma4:e4b)으로
텍스트 첫 토큰 0.105s 가 이미지가 붙으면 0.4~0.6s 로 간다. 시각이 필요 없는
질문에까지 물리면 대화 리듬이 죽는다.

**LLM 에게 "카메라가 필요하니?" 를 되묻지 않는다.** 왕복이 하나 더 붙어
지연이 두 배가 된다. 판별은 여기서 문자열로 끝낸다 — `motion.classify` 와 같은 결이다.

**애매하면 안 켠다.** 못 봐서 사용자가 "앞에 뭐 보여?" 로 다시 묻는 비용이,
매번 켜서 모든 턴이 느려지는 비용보다 싸다.
"""

import config

# 공백 유무는 STT 마다 흔들린다("이게 뭐야" / "이게뭐야") — 아래에서 둘 다 본다.
_TRIGGERS = (
    "이게 뭐", "이거 뭐", "이건 뭐", "그게 뭐", "저게 뭐",
    "뭐가 보여", "뭐 보여", "뭐가 보이", "보이니", "보이나요", "보여?",
    "앞에 뭐", "앞에 있", "여기 뭐",
    "내가 뭘", "내가 든", "들고 있", "입고 있",
    "몇 명", "몇 사람", "몇 개",
    "무슨 색", "어떤 색",
    "봐줘", "봐 줘", "이거 봐", "이것 봐", "읽어줘",
)


def _enabled() -> bool:
    return config.get("REACHY_VISION", "1").lower() not in ("0", "false", "no")


def wants_camera(text: str) -> bool:
    """이 발화가 **지금 앞을 봐야** 답할 수 있는 것인가.

    `뭐야` 처럼 흔한 말은 넣지 않는다 — "무선국 검사가 뭐야" 까지 카메라를 켜게 된다.
    지시대명사가 붙은 형태("이게 뭐")만 시각으로 본다.
    """
    if not text or not _enabled():
        return False
    flat = "".join(text.split())
    return any(k in text or "".join(k.split()) in flat for k in _TRIGGERS)
